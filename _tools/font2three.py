"""Convert a TTF/OTF (optionally a variable-font instance) into a three.js typeface font,
wrapped as a classic script so it works when the site is opened straight from disk.

usage: python font2three.py <font.ttf> <out.js> <name> [axis=value ...]
  e.g. python font2three.py Fredoka.ttf ../assets/fonts/fredoka-bold.js fredoka wght=700 wdth=100
"""
import json, sys
from fontTools.ttLib import TTFont
from fontTools.pens.basePen import BasePen

src, out, name, *axes = sys.argv[1:]
font = TTFont(src)
if 'fvar' in font:
    from fontTools.varLib import instancer
    loc = {a.split('=')[0]: float(a.split('=')[1]) for a in axes}
    font = instancer.instantiateVariableFont(font, loc)

upem = font['head'].unitsPerEm
S = 1000 / upem
gs, cmap, hmtx = font.getGlyphSet(), font.getBestCmap(), font['hmtx']
r = lambda v: round(v * S, 1)

class ThreePen(BasePen):
    """three.js 'o' command string. Note three's q/b order: end point first, then control points."""
    def __init__(self, glyphSet):
        super().__init__(glyphSet); self.cmd = []; self.xs = []
    def _p(self, *pts):
        for x, y in pts: self.cmd += [r(x), r(y)]; self.xs.append(x)
    def _moveTo(self, p): self.cmd.append('m'); self._p(p)
    def _lineTo(self, p): self.cmd.append('l'); self._p(p)
    def _qCurveToOne(self, c, p): self.cmd.append('q'); self._p(p, c)
    def _curveToOne(self, c1, c2, p): self.cmd.append('b'); self._p(p, c1, c2)
    def _closePath(self): pass

chars = [chr(c) for c in range(32, 127)] + list('’‘“”—–•©®…é')
glyphs = {}
for ch in chars:
    gname = cmap.get(ord(ch))
    if not gname: continue
    pen = ThreePen(gs); gs[gname].draw(pen)
    adv = hmtx[gname][0]
    o = ' '.join(str(v) for v in pen.cmd)
    glyphs[ch] = {'ha': r(adv), 'x_min': r(min(pen.xs)) if pen.xs else 0, 'x_max': r(max(pen.xs)) if pen.xs else 0, 'o': o}

hhea, head = font['hhea'], font['head']
data = {
    'glyphs': glyphs, 'familyName': name, 'resolution': 1000,
    'ascender': r(hhea.ascent), 'descender': r(hhea.descent),
    'underlinePosition': r(font['post'].underlinePosition), 'underlineThickness': r(font['post'].underlineThickness),
    'boundingBox': {'xMin': r(head.xMin), 'yMin': r(head.yMin), 'xMax': r(head.xMax), 'yMax': r(head.yMax)},
    'original_font_information': {'format': 0, 'fontFamily': name},
}
with open(out, 'w', encoding='utf-8') as f:
    f.write('/* generated by _tools/font2three.py — %s (SIL Open Font License) */\n' % name)
    f.write('(window.HPP_FONTS = window.HPP_FONTS || {})[%s] = ' % json.dumps(name))
    json.dump(data, f, ensure_ascii=False, separators=(',', ':'))
    f.write(';\n')
print(name, len(glyphs), 'glyphs')
